let lang = localStorage.getItem('elexio.lang') || 'fr';
const NODE_ORIGINAL = new WeakMap();
const ATTR_ORIGINAL = new WeakMap();
let isTranslating = false;
let domObserver = null;

export function currentLang(){ return lang; }
export function t(key){ if(!key) return key; const v = (DICT[lang] && DICT[lang][key]); return (v && v.length)? v : key; }

function formatParamValue(value) {
  const s = value == null ? '' : String(value);
  const v = DICT[lang] && DICT[lang][s];
  return (v && v.length) ? v : s;
}

/** Traduit un modèle contenant des variables `{nom}` puis remplace les variables.
 *  Les valeurs qui correspondent à une clé du dictionnaire (ex. nom de symbole)
 *  sont traduites aussi. Un tableau est joint par « , ». */
export function tf(key, params) {
  let out = t(key);
  if (!params) return out;
  for (const [name, value] of Object.entries(params)) {
    const text = Array.isArray(value)
      ? value.map(formatParamValue).join(', ')
      : formatParamValue(value);
    out = out.split('{' + name + '}').join(text);
  }
  return out;
}

function rememberOriginalNode(node) {
  if (!NODE_ORIGINAL.has(node)) NODE_ORIGINAL.set(node, node.nodeValue);
}

function rememberOriginalAttr(el, attr) {
  let map = ATTR_ORIGINAL.get(el);
  if (!map) { map = {}; ATTR_ORIGINAL.set(el, map); }
  if (map[attr] === undefined) map[attr] = el.getAttribute(attr);
}

function translateTextNode(node) {
  rememberOriginalNode(node);
  const original = NODE_ORIGINAL.get(node);
  const originalText = original.trim();
  const key = originalText || node.nodeValue.trim();
  if (!key) return;
  const translation = DICT[lang] && DICT[lang][key];
  if (translation === undefined) return;
  const newValue = original.replace(key, (translation && translation.length) ? translation : key);
  if (node.nodeValue !== newValue) node.nodeValue = newValue;
}

const TRANSLATABLE_ATTRS = ['title', 'placeholder', 'alt', 'aria-label'];

function translateElementAttributes(el) {
  for (const attr of TRANSLATABLE_ATTRS) {
    if (!el.hasAttribute(attr)) continue;
    rememberOriginalAttr(el, attr);
    const original = ATTR_ORIGINAL.get(el)[attr];
    const translation = DICT[lang] && DICT[lang][original];
    if (translation !== undefined) {
      const newValue = (translation && translation.length) ? translation : original;
      if (el.getAttribute(attr) !== newValue) el.setAttribute(attr, newValue);
    }
  }
}

function translateNode(node) {
  if (!node) return;
  if (node.nodeType === 3) {
    translateTextNode(node);
    return;
  }
  if (node.nodeType !== 1) return;
  translateElementAttributes(node);
  for (const child of Array.from(node.childNodes)) translateNode(child);
}

export function translateDocument() {
  if (!document.body) return;
  if (domObserver) domObserver.disconnect();
  isTranslating = true;
  try {
    translateNode(document.body);
  } finally {
    isTranslating = false;
    if (domObserver) domObserver.observe(document.body, { childList: true, subtree: true, characterData: true });
  }
}

export function setLang(l) {
  if (!DICT[l]) return;
  lang = l;
  localStorage.setItem('elexio.lang', l);
  translateDocument();
  try {
    document.dispatchEvent(new CustomEvent('elexio-langchange', { detail: { lang: l } }));
  } catch (err) { /* environnement sans CustomEvent (tests Node) */ }
}

export function applyInitialLang() {
  const sel = document.getElementById('lang-select');
  if (sel) sel.value = lang;
  if (document.body) translateDocument();
}

function startObserver() {
  if (!document.body || typeof MutationObserver === 'undefined') return;
  domObserver = new MutationObserver((records) => {
    if (lang === 'fr' || isTranslating) return;
    isTranslating = true;
    try {
      for (const record of records) {
        if (record.type === 'childList') {
          for (const n of record.addedNodes) translateNode(n);
        } else if (record.type === 'characterData' && record.target) {
          translateNode(record.target);
        }
      }
    } finally {
      isTranslating = false;
    }
  });
  domObserver.observe(document.body, { childList: true, subtree: true, characterData: true });
}

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', () => { startObserver(); }, { once: true });
} else {
  startObserver();
}
